/**
 * Project survey for /init. Every proposal comes from the repository (git
 * history, tracked files), so the interview only asks what the repository
 * cannot answer. Read-only; a broken config is reported, never a crash.
 *
 * Why the fix label first: the rework rate is only as good as the subject that
 * marks a fix. On the origin project 233 of 348 commits started with `fix(`,
 * so the absolute rate counted churn (see docs/evidence.md). The share is
 * measured over the commits the rework rate counts: those touching a
 * production path.
 */

import { existsSync, readFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { git } from "../core/git.mjs";
import { loadConfig, ConfigError, DEFAULTS } from "../core/config.mjs";
import { loadPathScopedRules, splitFrontMatter, parsePaths } from "../adapters/claude-code/rules-index.mjs";

/** Fewer commits than this and a share says little: the default stays. */
export const MIN_HISTORY = 30;
/** Commits read: how the project labels its work now, not years ago. */
export const RECENT_COMMITS = 300;
const MAX_LISTED = 10;

/** `type(scope)!: subject`. */
const CONVENTIONAL = /^[a-z]+(\([^)]*\))?!?:\s/;

// `\b` without the u flag treats Turkish letters as boundaries ("bug" in "bugün"); spell the letters out.
const L = "A-Za-z0-9_çğıöşüÇĞİÖŞÜ";

/**
 * Fix-label patterns. Compiled without flags, as metrics/szz.mjs compiles
 * `metrics.fixSubject`. Only a label at the start of the subject can be
 * proposed: a word inside it ("revert the fix") is a mention, not a repair,
 * and is reported as a weak signal.
 */
export const FIX_CANDIDATES = /** @type {const} */ ([
  { id: "conventional", anchored: true, pattern: DEFAULTS.metrics.fixSubject },
  { id: "verb", anchored: true, pattern: `^([Ff]ix(e[sd]|ing)?|[Bb]ug ?[Ff]ix|[Hh]ot ?[Ff]ix)(?![${L}])` },
  // Turkish subjects are often typed without diacritics: "duzeltme", "onarildi".
  { id: "turkish", anchored: true, pattern: "^([Dd][üu]zelt|[Oo]nar[ıi]l)" },
  { id: "mention", anchored: false, pattern: `(?<![${L}])([Ff]ix(e[sd]|ing)?|[Bb]ug ?[Ff]ix)(?![${L}])|(?<![${L}])[Dd][üu]zelt` },
]);

/** Test layouts the default `metrics.testRe` misses. */
export const TEST_ALTERNATIVES = /** @type {const} */ ([
  { id: "testDir", pattern: "(^|/)(tests?|spec)/" },
  { id: "suffix", pattern: "_(test|spec)\\.(go|py|rb|exs?)$" },
  { id: "pytest", pattern: "(^|/)test_[^/]+\\.py$" },
  { id: "className", pattern: "(Tests?|Spec)\\.(java|kt|cs|swift|php|scala)$" },
]);

const RISKY_NAME =
  /^(auth|authn|authz|authentication|authorization|security|permissions?|acl|rbac|migrations?|payments?|billing|invoices?|ledger|wallets?|accounting|orders?|risk|crypto|secrets?|sessions?|login|oauth|sso|ldap|saml)$/i;
const ROADMAP_FILE = /(^|\/)(roadmap|todo|backlog|plan|tasks|milestones?)(\.(md|markdown|txt|org))?$/i;
const ROADMAP_DOC = /(^|\/)docs?\/(.*\/)?[^/]*(roadmap|backlog|todo)[^/]*\.(md|markdown|txt)$/i;
// A roadmap split into one file per phase: docs/roadmap/phase-2.md.
const ROADMAP_DIR = /(^|\/)(roadmaps?|backlog|todo)\/[^/]+\.(md|markdown|txt)$/i;
const GENERATED_MARKER = /@generated|do not edit|auto-?generated|generated by/i;
// Base names and their fast variants; a project with a hundred check:* scripts lists its entry points only.
const COMMAND_SCRIPT = /^(test|lint|typecheck|type-check|check|verify|validate)(:(fast|quick|unit|ci))?$/;

/** @param {string} s */
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

/** `type(scope)!: ` in any language; the word must not hold spaces, so "faz 8:" is not a type. */
const TYPE_PREFIX = /^([^\s:()!]{1,24})(\([^)]*\))?!?:\s/;
const TR_LETTER = /[çğıöşüÇĞİÖŞÜ]/;
// Frequent Turkish words, also as typed without diacritics ("icin", "artik").
const TR_WORD = new RegExp(`(?<![${L}])(ve|ile|için|icin|artık|artik|değil|degil|yok|bir|bu|olarak|gibi|daha|çok|cok|sonra|önce|once|yeni|eski|ama|her|hiç|hic|yalnız|yalniz)(?![${L}])`, "i");
const EN_WORD = /\b(the|and|for|with|to|of|in|is|on|from|when|now|not|an?)\b/i;

/**
 * How the project writes commits now: the language of recent subjects and the
 * types in front of them. A guess for /ennyn:init to offer, not a rule.
 * @param {string[]} subjects
 */
export function commitStyle(subjects) {
  let tr = 0;
  let en = 0;
  /** @type {Map<string, number>} */
  const types = new Map();
  for (const s of subjects) {
    if (TR_LETTER.test(s) || TR_WORD.test(s)) tr++;
    else if (EN_WORD.test(s)) en++;
    const m = TYPE_PREFIX.exec(s);
    if (m) types.set(m[1], (types.get(m[1]) ?? 0) + 1);
  }
  const typed = [...types.values()].reduce((a, b) => a + b, 0);
  return {
    language: { guess: tr + en < 5 ? null : tr > en ? "tr" : "en", tr, en },
    types: [...types].sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1)).slice(0, MAX_LISTED).map(([type, n]) => ({ type, n })),
    typedShare: subjects.length ? typed / subjects.length : null,
  };
}

/**
 * @typedef {{ subject: string, paths: string[] }} RecentCommit
 * @typedef {{ exclude: RegExp, test: RegExp }} PathPatterns
 * @typedef {{ id: string, anchored: boolean, pattern: string, matches: number, share: number | null, examples: string[] }} FixCandidate
 * @typedef {{ commits: number, conventionalShare: number | null, candidates: FixCandidate[], proposal: string | null, pick: string | null,
 *   matches: number, share: number | null, examples: string[], reason: "ok" | "majority" | "weak" | "none" | "tooFew" }} FixProposal
 *   `matches` / `share` / `examples` belong to the proposal (or, when weak, to the mentions).
 */

/**
 * Recent non-merge commits with their subject and touched paths. `-z` keeps
 * paths raw: without it git C-quotes names holding quotes, backslashes or tabs.
 * @param {string} cwd
 * @param {number} [limit]
 * @returns {RecentCommit[]} newest first; [] outside a repository or without commits
 */
export function recentCommits(cwd, limit = RECENT_COMMITS) {
  if (!git(["rev-parse", "--verify", "-q", "HEAD"], { cwd, allowFail: true })) return [];
  const out = git(["log", "-z", "--no-merges", "--no-renames", `-n${limit}`, "--name-only", "--format=%x01%s"], { cwd });
  return out
    .split("\x01")
    .slice(1)
    .map((chunk) => {
      const nul = chunk.indexOf("\0");
      if (nul === -1) return { subject: chunk, paths: [] };
      return { subject: chunk.slice(0, nul), paths: chunk.slice(nul + 1).replace(/^\n/, "").split("\0").filter(Boolean) };
    });
}

/**
 * Subjects of the commits the rework rate counts as candidates: those touching a production path.
 * @param {RecentCommit[]} commits
 * @param {PathPatterns} re
 */
export function productionSubjects(commits, re) {
  return commits.filter((c) => c.paths.some((p) => !re.exclude.test(p) && !re.test.test(p))).map((c) => c.subject);
}

/**
 * The config's path patterns; one that does not compile is reported and the default is used.
 * @param {any} config
 * @param {string[]} problems
 * @returns {{ re: PathPatterns, excludeRe: string, testRe: string }}
 */
export function pathPatterns(config, problems) {
  const pick = (/** @type {"excludeRe" | "testRe"} */ key) => {
    try {
      return { source: String(config.metrics[key]), re: new RegExp(config.metrics[key]) };
    } catch (e) {
      problems.push(`"metrics.${key}" is not a valid regular expression (${/** @type {Error} */ (e).message}); the default is used`);
      return { source: DEFAULTS.metrics[key], re: new RegExp(DEFAULTS.metrics[key]) };
    }
  };
  const exclude = pick("excludeRe");
  const test = pick("testRe");
  return { re: { exclude: exclude.re, test: test.re }, excludeRe: exclude.source, testRe: test.source };
}

/**
 * Propose the fix label that fits the history: every anchored pattern that
 * matches, minus those another one covers (conventional `fix:` inside `Fix…`;
 * on equal sets the more specific stays), joined into one alternation. A
 * project that writes both `fix(ui):` and `düzeltme:` gets both. Matching more
 * than half of the commits is flagged: there the label does not separate
 * repairs from ordinary work. Only mentions inside subjects → "weak", nothing
 * proposed.
 * @param {string[]} subjects
 * @returns {FixProposal}
 */
export function proposeFixSubject(subjects) {
  const n = subjects.length;
  /** @type {Map<string, Set<number>>} */
  const hitsOf = new Map();
  /** @type {FixCandidate[]} */
  const candidates = FIX_CANDIDATES.map((c) => {
    const re = new RegExp(c.pattern);
    const hits = new Set(subjects.flatMap((s, i) => (re.test(s) ? [i] : [])));
    hitsOf.set(c.id, hits);
    const examples = [...hits].slice(0, 3).map((i) => subjects[i]);
    return { id: c.id, anchored: c.anchored, pattern: c.pattern, matches: hits.size, share: n ? hits.size / n : null, examples };
  });
  const conventionalShare = n ? subjects.filter((s) => CONVENTIONAL.test(s)).length / n : null;
  const base = { commits: n, conventionalShare, candidates };
  const empty = { proposal: null, pick: null, matches: 0, share: null, examples: [] };
  if (n < MIN_HISTORY) return { ...base, ...empty, reason: "tooFew" };

  const anchored = candidates.filter((c) => c.anchored && c.matches > 0);
  const covered = (/** @type {FixCandidate} */ c, /** @type {FixCandidate} */ o) => [...(hitsOf.get(c.id) ?? [])].every((i) => hitsOf.get(o.id)?.has(i));
  const kept = anchored.filter((c, i) => !anchored.some((o, j) => o !== c && covered(c, o) && (o.matches > c.matches || j < i)));
  if (kept.length) {
    const union = new Set(kept.flatMap((c) => [...(hitsOf.get(c.id) ?? [])]));
    const proposal = kept.length === 1 ? kept[0].pattern : kept.map((c) => `(?:${c.pattern})`).join("|");
    const examples = [...union].sort((a, b) => a - b).slice(0, 3).map((i) => subjects[i]);
    const reason = union.size * 2 > n ? "majority" : "ok";
    return { ...base, proposal, pick: kept.map((c) => c.id).join("+"), matches: union.size, share: union.size / n, examples, reason };
  }
  const mention = candidates.find((c) => !c.anchored && c.matches > 0);
  if (mention) return { ...base, proposal: null, pick: mention.id, matches: mention.matches, share: mention.share, examples: mention.examples, reason: "weak" };
  return { ...base, ...empty, reason: "none" };
}

/** @param {string} cwd */
function trackedFiles(cwd) {
  const out = git(["-c", "core.quotePath=false", "ls-files", "-z"], { cwd, allowFail: true });
  return out.split("\0").filter(Boolean);
}

/** @param {string} path */
function hasGeneratedMarker(path) {
  try {
    return GENERATED_MARKER.test(readFileSync(path, "utf8").slice(0, 1024));
  } catch {
    return false;
  }
}

/**
 * Paths rewritten in many recent commits that the rework rate still counts.
 * Generated output looks like this; so does a central source file, which is
 * why the result is a question for the user, not an exclusion. Each path
 * carries the `excludeRe` alternative that would exclude exactly it.
 * @param {RecentCommit[]} commits
 * @param {string} cwd
 * @param {PathPatterns} re
 */
export function churnPaths(commits, cwd, re) {
  const n = commits.length;
  if (n < MIN_HISTORY) return { commits: n, min: null, paths: [] };
  /** @type {Map<string, number>} */
  const counts = new Map();
  for (const c of commits) for (const p of new Set(c.paths)) counts.set(p, (counts.get(p) ?? 0) + 1);
  const min = Math.max(10, Math.ceil(n / 4));
  const paths = [...counts]
    .filter(([p, c]) => c >= min && !re.exclude.test(p) && !re.test.test(p))
    .sort((a, b) => b[1] - a[1] || (a[0] < b[0] ? -1 : 1))
    .slice(0, MAX_LISTED)
    .map(([path, c]) => ({ path, commits: c, share: c / n, generatedMarker: hasGeneratedMarker(join(cwd, path)), excludePattern: `^${escapeRe(path)}$` }));
  return { commits: n, min, paths };
}

/**
 * @param {string[]} files
 * @param {string} testRe the current `metrics.testRe`
 */
export function testLayout(files, testRe) {
  const current = new RegExp(testRe);
  const missed = files.filter((f) => !current.test(f));
  const alternatives = TEST_ALTERNATIVES.map((a) => {
    const re = new RegExp(a.pattern);
    const hits = missed.filter((f) => re.test(f));
    return { id: a.id, pattern: a.pattern, files: hits.length, examples: hits.slice(0, 3) };
  }).filter((a) => a.files > 0);
  return {
    matched: files.length - missed.length,
    alternatives,
    proposal: alternatives.length ? [testRe, ...alternatives.map((a) => a.pattern)].join("|") : null,
  };
}

/**
 * Paths whose name says auth, security, migrations, payments, ledger… A
 * matching directory covers everything below it (the first matching segment
 * is taken, so no listed directory sits inside another); in a flat layout the
 * file itself is listed (`app/security.py`). Test and excluded paths do not count.
 * @param {string[]} files
 * @param {PathPatterns} re
 */
export function riskyPaths(files, re) {
  /** @type {Map<string, { files: number, glob: string }>} */
  const found = new Map();
  for (const f of files) {
    if (re.exclude.test(f) || re.test.test(f)) continue;
    const parts = f.split("/");
    const i = parts.slice(0, -1).findIndex((s) => RISKY_NAME.test(s));
    if (i !== -1) {
      const dir = parts.slice(0, i + 1).join("/");
      const prev = found.get(dir);
      found.set(dir, { files: (prev?.files ?? 0) + 1, glob: `${dir}/**` });
    } else if (RISKY_NAME.test(parts[parts.length - 1].replace(/\.[^.]*$/, ""))) {
      found.set(f, { files: 1, glob: f });
    }
  }
  return [...found.keys()]
    .sort()
    .slice(0, MAX_LISTED)
    .map((path) => ({ path, .../** @type {{ files: number, glob: string }} */ (found.get(path)) }));
}

/**
 * Files that read like a roadmap or backlog, with their checkbox counts.
 * @param {string} cwd
 * @param {string[]} files
 */
export function roadmapFiles(cwd, files) {
  return files
    .filter((f) => (ROADMAP_FILE.test(f) || ROADMAP_DOC.test(f) || ROADMAP_DIR.test(f)) && !/(^|\/)archive\//i.test(f))
    .slice(0, MAX_LISTED * 2)
    .map((path) => {
      let text = "";
      try {
        text = readFileSync(join(cwd, path), "utf8");
      } catch {
        // Listed by git but unreadable here: counts stay zero.
      }
      return {
        path,
        open: (text.match(/^\s*[-*+] \[ \]/gm) ?? []).length,
        done: (text.match(/^\s*[-*+] \[[xX]\]/gm) ?? []).length,
        lines: text === "" ? 0 : text.split("\n").length,
      };
    });
}

/** @param {string} cwd */
function githubRepo(cwd) {
  const url = git(["remote", "get-url", "origin"], { cwd, allowFail: true });
  const m = /github\.com[:/]([^/\s]+)\/([^/\s]+?)(\.git)?\/?$/.exec(url);
  return m ? `${m[1]}/${m[2]}` : null;
}

/**
 * Test, lint and mutation commands the repository declares at its root.
 * @param {string} cwd
 */
export function projectCommands(cwd) {
  /** @type {string[]} */
  const commands = [];
  /** @type {string | null} */
  let mutation = null;
  const read = (/** @type {string} */ name) => {
    try {
      return readFileSync(join(cwd, name), "utf8");
    } catch {
      return null;
    }
  };
  const pkg = read("package.json");
  if (pkg) {
    try {
      const scripts = JSON.parse(pkg)?.scripts;
      if (scripts && typeof scripts === "object") {
        for (const name of Object.keys(scripts).sort()) {
          if (COMMAND_SCRIPT.test(name)) commands.push(name === "test" ? "npm test" : `npm run ${name}`);
          if (mutation === null && /stryker/.test(String(scripts[name]))) mutation = `npm run ${name}`;
        }
      }
    } catch {
      // A broken package.json declares nothing.
    }
  }
  const make = read("Makefile");
  if (make) for (const m of make.matchAll(/^(test|check|lint)\s*:/gm)) commands.push(`make ${m[1]}`);
  // A project's own gate script often runs everything the commands above run, and more.
  for (const name of ["validate", "test", "check", "ci"]) if (existsSync(join(cwd, "scripts", `${name}.sh`))) commands.push(`./scripts/${name}.sh`);
  const py = (read("pyproject.toml") ?? "") + (read("pytest.ini") ?? "") + (read("setup.cfg") ?? "");
  if (/pytest/.test(py)) commands.push("pytest");
  if (/\[tool\.mutmut\]|\[mutmut\]/.test(py)) mutation ??= "mutmut run";
  if (existsSync(join(cwd, "go.mod"))) commands.push("go test ./...");
  if (existsSync(join(cwd, "Cargo.toml"))) commands.push("cargo test");
  if (existsSync(join(cwd, ".cargo", "mutants.toml"))) mutation ??= "cargo mutants";
  if (mutation === null && ["stryker.conf.js", "stryker.conf.mjs", "stryker.conf.json", "stryker.config.js", "stryker.config.mjs", "stryker.config.json"].some((f) => existsSync(join(cwd, f)))) {
    mutation = "npx stryker run";
  }
  return { commands: [...new Set(commands)].slice(0, 8), mutation };
}

/** Instruction files Claude Code loads in every session; checked on disk, as CLAUDE.local.md is never tracked. */
const ALWAYS_FILES = ["CLAUDE.md", ".claude/CLAUDE.md", "CLAUDE.local.md"];
/** Files other agents read; Claude Code does not, but a rule in them still contradicts the cycle. */
const OTHER_FILES = ["AGENTS.md", "GEMINI.md", ".cursorrules", ".github/copilot-instructions.md", "CONTRIBUTING.md"];
// Names that say "this runs a development loop" or "this reviews a change", in English and Turkish,
// as whole parts of a hyphenated name ("preview-builder" is not a reviewer).
export const CYCLE_SKILL = /(^|[-_])(cycle|phase|faz|d[öo]ng[üu]|sprint|loop)([-_]|$)/i;
export const REVIEWER = /(^|[-_])(review|checker|validator|verif|critic|pentest|audit|inceleme|g[öo]zden-?ge[çc]ir|denet[çc]i|do[ğg]rulay[ıi]c[ıi]|incele[iy]ici)/i;
// A line that sets a commit rule names the message, its language, its length or a ban (score 2); one
// that only starts with "commit" (a step heading) scores 1 and fills what is left. A line that only
// mentions commits, or SQL ("COMMIT;", BEGIN / ROLLBACK), is left out.
const RULE_START = /^[\s\-*>#`|]*(\d+[.)]\s*)?[\s*`_]*commit/i;
const RULE_WORDS = /(mesaj|message|konu|subject|format|\bdil\b|language|türkçe|turkish|english|ingilizce|tek satır|one[- ]line|yasak|never|asla|co-authored|no-verify)/i;
const SQL = /\bCOMMIT\s*;|\b(BEGIN|ROLLBACK)\b/;

/** @param {string} path */
function readText(path) {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return null;
  }
}

/**
 * A JSON file's top-level object: `null` when absent, `"unreadable"` when it does not parse.
 * @param {string} path
 * @returns {Record<string, any> | null | "unreadable"}
 */
function readJson(path) {
  const text = readText(path);
  if (text === null) return null;
  try {
    const v = JSON.parse(text);
    return v && typeof v === "object" && !Array.isArray(v) ? v : "unreadable";
  } catch {
    return "unreadable";
  }
}

/**
 * Entries of a directory, following symlinks (a linked skill or agent counts), NFC-normalized.
 * @param {string} dir @param {(name: string) => boolean} keep
 */
function names(dir, keep) {
  let list = [];
  try {
    list = readdirSync(dir);
  } catch {
    return [];
  }
  return list.filter((n) => existsSync(join(dir, n)) && keep(n)).map((n) => n.normalize("NFC")).sort();
}

/**
 * Markdown files below a directory, relative, "/"-separated; linked directories followed.
 * A walk of its own: readdirSync's recursive option is missing in Node 20.0.
 * @param {string} dir @param {string} [rel] @param {number} [depth]
 * @returns {string[]}
 */
function markdownBelow(dir, rel = "", depth = 0) {
  let entries = [];
  try {
    entries = readdirSync(join(dir, rel));
  } catch {
    return [];
  }
  /** @type {string[]} */
  const out = [];
  for (const name of entries) {
    const path = rel ? `${rel}/${name}` : name;
    let st;
    try {
      st = statSync(join(dir, path));
    } catch {
      continue;
    }
    if (st.isDirectory() && depth < 8) out.push(...markdownBelow(dir, path, depth + 1));
    else if (st.isFile() && name.endsWith(".md")) out.push(path);
  }
  return out.sort();
}

/** @param {string} text */
export function commitRuleLines(text) {
  return text
    .split("\n")
    .map((l) => l.trim())
    .filter((l) => /commit/i.test(l) && !SQL.test(l))
    .map((l) => ({ l, rank: (RULE_WORDS.test(l) ? 2 : 0) + (RULE_START.test(l) ? 1 : 0) }))
    .filter((x) => x.rank > 0)
    .sort((a, b) => b.rank - a.rank)
    .slice(0, 8)
    .map(({ l }) => (l.length > 160 ? l.slice(0, 157) + "…" : l));
}

/**
 * The agent setup the project already has. `instructions` lists every
 * instruction and rule file with its size, when it loads ("always": every
 * session; "on-demand": when a matching path is touched; "other": read by
 * other agents only) and the lines that set a commit rule. /ennyn:init asks how
 * Ennyn's cycle and reviewers sit next to what is there, and finds every
 * commit rule it would contradict.
 * @param {string} cwd
 * @param {string[]} files tracked files (nested CLAUDE.md / AGENTS.md are found there)
 */
export function agentSetup(cwd, files) {
  /** @type {Array<{ path: string, loads: "always" | "on-demand" | "other" }>} */
  const candidates = [
    ...ALWAYS_FILES.map((path) => ({ path, loads: /** @type {const} */ ("always") })),
    ...markdownBelow(join(cwd, ".claude", "rules")).map((f) => {
      const path = `.claude/rules/${f}`;
      const { frontMatter } = splitFrontMatter(readText(join(cwd, path)) ?? "");
      const patterns = frontMatter === null ? null : parsePaths(frontMatter);
      return { path, loads: /** @type {"on-demand" | "always"} */ (patterns && patterns.length ? "on-demand" : "always") };
    }),
    ...files
      .filter((f) => /(^|\/)CLAUDE\.md$/.test(f) && !ALWAYS_FILES.includes(f))
      .slice(0, MAX_LISTED)
      .map((path) => ({ path, loads: /** @type {const} */ ("on-demand") })),
    ...OTHER_FILES.map((path) => ({ path, loads: /** @type {const} */ ("other") })),
    ...files
      .filter((f) => /(^|\/)AGENTS\.md$/.test(f) && !OTHER_FILES.includes(f))
      .slice(0, MAX_LISTED)
      .map((path) => ({ path, loads: /** @type {const} */ ("other") })),
  ];
  const instructions = candidates.flatMap(({ path, loads }) => {
    const text = readText(join(cwd, path));
    return text === null ? [] : [{ path, loads, bytes: Buffer.byteLength(text, "utf8"), commitLines: commitRuleLines(text) }];
  });
  const size = { always: 0, onDemand: 0, other: 0 };
  for (const i of instructions) size[i.loads === "always" ? "always" : i.loads === "on-demand" ? "onDemand" : "other"] += i.bytes;

  const skills = names(join(cwd, ".claude", "skills"), (n) => existsSync(join(cwd, ".claude", "skills", n, "SKILL.md")));
  const agents = names(join(cwd, ".claude", "agents"), (n) => n.endsWith(".md")).map((n) => n.replace(/\.md$/, ""));
  const commands = markdownBelow(join(cwd, ".claude", "commands")).map((f) => f.slice(0, -3).normalize("NFC"));
  /** @type {string[]} */
  const unreadable = [];
  /** @type {Set<string>} */
  const events = new Set();
  for (const path of [".claude/settings.json", ".claude/settings.local.json"]) {
    const json = readJson(join(cwd, path));
    if (json === "unreadable") unreadable.push(path);
    else for (const e of Object.keys(json?.hooks ?? {})) events.add(e);
  }
  const mcp = readJson(join(cwd, ".mcp.json"));
  if (mcp === "unreadable") unreadable.push(".mcp.json");
  return {
    instructions,
    size,
    skills,
    agents,
    commands: commands.slice(0, 20),
    hooks: [...events].sort(),
    mcpServers: mcp === "unreadable" ? [] : Object.keys(mcp?.mcpServers ?? {}).sort(),
    unreadable,
    overlaps: {
      cycle: [...skills.filter((s) => CYCLE_SKILL.test(s)), ...commands.filter((c) => CYCLE_SKILL.test(c.split("/").pop() ?? "")).map((c) => `/${c}`)],
      reviewers: agents.filter((a) => REVIEWER.test(a)),
    },
  };
}

/**
 * @param {{ cwd: string, env?: NodeJS.ProcessEnv }} opts
 */
export function scanProject({ cwd, env = process.env }) {
  /** @type {any} */
  let config = DEFAULTS;
  /** @type {string | null} */
  let configPath = null;
  // false: the config did not load and every value below is a default, not the project's.
  let loaded = true;
  /** @type {string[]} */
  const problems = [];
  try {
    config = loadConfig({ cwd, env });
    configPath = config.configPath;
  } catch (e) {
    if (!(e instanceof ConfigError)) throw e;
    configPath = resolve(cwd, env.ENNYN_CONFIG || ".ennyn/config.json");
    loaded = false;
    problems.push(...e.problems);
  }
  const patterns = pathPatterns(config, problems);
  const repo = git(["rev-parse", "--git-dir"], { cwd, allowFail: true }) !== "";
  const files = repo ? trackedFiles(cwd) : [];
  const commits = repo ? recentCommits(cwd) : [];
  const graphPath = resolve(cwd, config.paths.graph);
  const handoffPath = resolve(cwd, config.paths.handoff);
  return {
    repository: repo,
    config: { path: configPath, loaded, problems },
    metrics: { excludeRe: patterns.excludeRe, testRe: patterns.testRe },
    graph: { path: graphPath, exists: existsSync(graphPath), exports: config.graph.exports },
    handoff: { path: handoffPath, exists: existsSync(handoffPath) },
    fixSubject: { current: config.metrics.fixSubject, ...proposeFixSubject(productionSubjects(commits, patterns.re)) },
    commitStyle: commitStyle(commits.map((c) => c.subject)),
    churn: churnPaths(commits, cwd, patterns.re),
    tests: testLayout(files, patterns.testRe),
    risky: riskyPaths(files, patterns.re),
    roadmap: roadmapFiles(cwd, files),
    github: repo ? githubRepo(cwd) : null,
    pathScopedRules: loadPathScopedRules(cwd).length,
    agentSetup: agentSetup(cwd, files),
    ...projectCommands(cwd),
  };
}
